export function getCatById(id: string) {
  const cat = getAllCats().find((c) => c.id === id);
  return cat ? applyCatProfileOverrides(cat) : undefined;
}

export function getAllCats() {
  const intakeCats = loadCompanionIntakeCats().map(intakeRecordToAdminCat);
  const seedIds = new Set(adminCats.map((cat) => cat.id));
  return [...intakeCats.filter((cat) => !seedIds.has(cat.id)), ...adminCats].map(
    applyCatProfileOverrides,
  );
}

export function getDonorById(id: string) {
  return donors.find((d) => d.id === id);
}
